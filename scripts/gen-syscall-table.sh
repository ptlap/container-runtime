#!/usr/bin/env bash
# Generate the syscall name/number tables in src/seccomp/.
#
# Syscall numbers are permanent kernel ABI, so the tables are generated once and
# committed rather than resolved at build time. That keeps the build free of
# host headers and cross-compilation surprises, and a unit test cross-checks a
# sample of the entries against libc so a bad regeneration cannot go unnoticed.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$REPO_ROOT/src/seccomp"
LIBC_DIR=""
ARCHES="x86_64 aarch64"

usage() {
    cat <<'EOF'
Usage: scripts/gen-syscall-table.sh [options]

  --libc PATH    Path to the vendored libc crate source (default: autodetect
                 the newest libc-0.2.* under ~/.cargo/registry)
  --arch LIST    Space separated architectures (default: "x86_64 aarch64")
  --out DIR      Output directory (default: src/seccomp)
  -h, --help     Show this help

Commit the generated files. Re-run after bumping libc.
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --libc) LIBC_DIR="$2"; shift 2 ;;
        --arch) ARCHES="$2"; shift 2 ;;
        --out) OUT_DIR="$2"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "error: unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
done

if [ -z "$LIBC_DIR" ]; then
    LIBC_DIR="$(find "$HOME/.cargo/registry/src" -maxdepth 2 -type d -name 'libc-0.2.*' 2>/dev/null | sort -V | tail -1)"
fi

[ -n "$LIBC_DIR" ] && [ -d "$LIBC_DIR" ] || {
    echo "error: could not locate the libc crate source; pass --libc PATH" >&2
    exit 2
}

LIBC_VERSION="$(basename "$LIBC_DIR")"
echo "using $LIBC_VERSION"

source_for_arch() {
    case "$1" in
        x86_64) echo "$LIBC_DIR/src/unix/linux_like/linux/gnu/b64/x86_64/not_x32.rs" ;;
        aarch64) echo "$LIBC_DIR/src/unix/linux_like/linux/gnu/b64/aarch64/mod.rs" ;;
        *) return 1 ;;
    esac
}

for arch in $ARCHES; do
    source_file="$(source_for_arch "$arch")" || {
        echo "error: unsupported architecture: $arch" >&2
        exit 2
    }
    [ -f "$source_file" ] || { echo "error: missing libc source: $source_file" >&2; exit 2; }

    out_file="$OUT_DIR/syscalls_${arch}.rs"
    # LC_ALL=C keeps the byte ordering that Rust's binary search expects;
    # locale collation ignores underscores and silently breaks lookups.
    entries="$(grep -oE '^pub const SYS_[a-z0-9_]+: c_long = [0-9]+;' "$source_file" \
        | sed -E 's/^pub const SYS_([a-z0-9_]+): c_long = ([0-9]+);$/\1 \2/' \
        | LC_ALL=C sort -u)"
    count="$(printf '%s\n' "$entries" | grep -c . || true)"
    [ "$count" -gt 0 ] || { echo "error: no syscalls parsed for $arch" >&2; exit 1; }

    {
        echo "//! @generated by scripts/gen-syscall-table.sh from $LIBC_VERSION"
        echo "//!"
        echo "//! Syscall numbers for $arch. Do not edit by hand; re-run the generator."
        echo
        echo "use super::syscalls::SyscallEntry;"
        echo
        echo "/// Sorted by name."
        echo "#[rustfmt::skip]"
        echo "pub(super) const TABLE: &[SyscallEntry] = &["
        printf '%s\n' "$entries" | LC_ALL=C sort -k1,1 | while read -r name number; do
            printf '    SyscallEntry { name: "%s", number: %s },\n' "$name" "$number"
        done
        echo "];"
        echo
        echo "/// Sorted by number."
        echo "#[rustfmt::skip]"
        echo "pub(super) const BY_NUMBER: &[SyscallEntry] = &["
        printf '%s\n' "$entries" | LC_ALL=C sort -k2,2n | while read -r name number; do
            printf '    SyscallEntry { name: "%s", number: %s },\n' "$name" "$number"
        done
        echo "];"
    } >"$out_file"

    echo "wrote $out_file ($count syscalls)"
done
